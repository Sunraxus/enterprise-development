namespace EstateAgency.Domain.Enums;

/// <summary>
/// Тип объекта недвижимости в предметной области риэлторского агентства; используется для классификации заявок и аналитики.
/// </summary>
public enum TypeRealEstate
{
    /// <summary>
    /// Квартира в многоквартирном доме.
    /// </summary>
    Apartment,

    /// <summary>
    /// Индивидуальный жилой дом с земельным участком.
    /// </summary>
    House,

    /// <summary>
    /// Коммерческое помещение для торговли или услуг (не офис).
    /// </summary>
    Commercial,

    /// <summary>
    /// Офисное помещение в бизнес‑центре либо административном здании.
    /// </summary>
    Office,

    /// <summary>
    /// Складское помещение или логистический объект.
    /// </summary>
    Warehouse
}
